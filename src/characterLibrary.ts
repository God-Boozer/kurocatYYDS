const NORMALIZED: { entry: CharacterPalette; keys: string[] }[] = LIBRARY.map((entry) => ({
  entry,
  keys: [entry.name, entry.id, ...entry.aliases].map((key) => normalize(key)),
}));

function normalize(value: string): string {
  return value
    .toLowerCase()
    .replace(/[\s\-_·.。,'"'"'！!？?~～]/g, '')
    .trim();
}

/** Look up a character by (part of) its name in the bundled library. */
export function findInLibrary(query: string): CharacterPalette[] {
  const q = normalize(query);
  if (!q) return [];
  const exact: CharacterPalette[] = [];
  const startsWith: CharacterPalette[] = [];
  const contains: CharacterPalette[] = [];
  for (const { entry, keys } of NORMALIZED) {
    for (const key of keys) {
      if (key === q) {
        exact.push(entry);
        break;
      }
      if (key.startsWith(q)) {
        startsWith.push(entry);
        break;
      }
      if (key.includes(q)) {
        contains.push(entry);
        break;
      }
    }
  }
  const seen = new Set<string>();
  const ordered = [...exact, ...startsWith, ...contains];
  return ordered.filter((entry) => {
    if (seen.has(entry.id)) return false;
    seen.add(entry.id);
    return true;
  });
}

export function allLibraryCharacters(): CharacterPalette[] {
  return LIBRARY.slice();
}

export function libraryPaletteById(id: string): CharacterPalette | null {
  return LIBRARY.find((entry) => entry.id === id) ?? null;
}
